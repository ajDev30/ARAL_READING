$pdo = new PDO("mysql:host=db;dbname=aral_reading_db", "andrew", "1234");
$pdo->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);

foreach ($blocks as $block) {
    $block = trim($block);
    if (empty($block)) continue;

    $lines = explode("\n", $block);
    $header_parts = explode("—", $lines[0]);
    $grade_num = trim($header_parts[0]);
    $grade = "Grade " . $grade_num;
    $title = trim($header_parts[1]);

    $passage = [];
    $questions_block = [];
    $in_questions = false;
    $answer_key = null;

    for ($i = 1; $i < count($lines); $i++) {
        $line = trim($lines[$i]);
        if ($line === "Questions") {
            $in_questions = true;
            continue;
        }
        if (strpos($line, "Answer Key:") === 0) {
            $answer_key = $line;
            continue;
        }

        if ($in_questions) {
            $questions_block[] = $line;
        } else {
            if ($line !== "") {
                $passage[] = $line;
            }
        }
    }

    // Parse Answer Key
    $ans_map = [];
    if ($answer_key) {
        $key_str = str_replace("Answer Key:", "", $answer_key);
        $parts = explode(",", $key_str);
        foreach ($parts as $p) {
            $p = trim($p);
            if (strpos($p, "-") !== false) {
                list($qnum, $qans) = explode("-", $p);
                $ans_map[(int)$qnum] = trim($qans);
            }
        }
    }

    $q_text = implode("\n", $questions_block);
    $qs = preg_split('/\d+\.\s+/', $q_text);
    
    $questions_json = [];
    $q_idx = 1;

    foreach ($qs as $q) {
        $q = trim($q);
        if (empty($q)) continue;

        $qlines = explode("\n", $q);
        $q_title = trim($qlines[0]);
        $options = [];

        for ($j = 1; $j < count($qlines); $j++) {
            $opt = trim($qlines[$j]);
            if (empty($opt)) continue;
            // Remove A., B., C., D.
            $opt = preg_replace('/^[A-D]\.\s+/', '', $opt);
            $options[] = $opt;
        }

        $correct_ans_char = isset($ans_map[$q_idx]) ? $ans_map[$q_idx] : 'A';
        $correct_idx = ord($correct_ans_char) - ord('A');

        $questions_json[] = [
            "type" => "multichoice",
            "question" => $q_title,
            "options" => $options,
            "correct" => $correct_idx
        ];
        $q_idx++;
    }

    $passage_html = "<p>" . implode("</p>\n<p>", $passage) . "</p>";
    $json_str = json_encode($questions_json);

    // check if grade exists
    $stmt = $pdo->prepare("SELECT id FROM reading_passages WHERE grade_level = ?");
    $stmt->execute([$grade]);
    $row = $stmt->fetch();

    if ($row) {
        echo "Updating $grade...\n";
        $update = $pdo->prepare("UPDATE reading_passages SET title = ?, passage_text = ?, questions_json = ? WHERE id = ?");
        $update->execute([$title, $passage_html, $json_str, $row['id']]);
    } else {
        echo "Inserting $grade...\n";
        $insert = $pdo->prepare("INSERT INTO reading_passages (title, grade_level, passage_text, questions_json) VALUES (?, ?, ?, ?)");
        $insert->execute([$title, $grade, $passage_html, $json_str]);
    }
}
echo "Done!\n";
